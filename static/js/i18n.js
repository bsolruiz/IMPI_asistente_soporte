function getLang() {
  const l = localStorage.getItem("impi_idioma");
  return I18N[l] ? l : "es";
}

function setLang(l) {
  if (I18N[l]) {
    localStorage.setItem("impi_idioma", l);
    applyI18n();
    document.dispatchEvent(new CustomEvent("idioma-cambiado", { detail: l }));
  }
}

// t('clave') o t('clave', {x: 'algo'}) para textos con {x}
function t(key, vars) {
  const lang = getLang();
  let s = (I18N[lang] && I18N[lang][key]) || I18N.es[key] || key;
  if (vars) {
    for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
  }
  return s;
}

// Reemplaza todos los textos marcados con data-i18n / data-i18n-ph / data-i18n-title
function applyI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach(function (el) {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  root.querySelectorAll("[data-i18n-title]").forEach(function (el) {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  document.documentElement.lang = getLang();
}

document.addEventListener("DOMContentLoaded", function () { applyI18n(); });
